#!/usr/bin/env node
const fs = require("fs");
const path = require("path");
const vm = require("vm");

let fails = 0;
function ok(cond, msg) {
  if (!cond) {
    fails += 1;
    console.error("FAIL " + msg);
  } else {
    console.log("ok   " + msg);
  }
}

const file = path.join(__dirname, "..", "data", "demo-world.json");
const raw = fs.readFileSync(file, "utf8");
const data = JSON.parse(raw);
const expected = {
  version: 5,
  label: "DEMO",
  seedLiveBlob: false,
  purpose: "How / examples / setup fixtures. Shop niches plus AIA project, world users, connections, AI agents, and people. Not live clients. Do not mix into the 5 live workspaces.",
  note: "Full card copy is generated by setup-demo.js (65 desks). seedLiveBlob stays false."
};
ok(JSON.stringify(data) === JSON.stringify(expected), "demo-world payload is exact compact fixture");

const HOW = ["life","estate","assets","auto","vita","legal","land","btr","fund","storm","gc","practice","pm","storage"];
const EXTRA = ["church","repair","delivery","school","files","bakery","salon","movers","daycare","photo","tax","gym","realty","pest","tow","lawn","florist","vet","clean","boutique","ink","brewery","catering","groom","books","funeral","notary","farm","venue","appliance","junk","hoa","pool","detail","music","hvac","build","world","pipes","agent","people","rules","drop","pack","family","print","lock","tree","snow","senior","foodtruck"];

async function main() {
  const setupPath = path.join(__dirname, "..", "setup-demo.js");
  const setupSrc = fs.readFileSync(setupPath, "utf8");
  const sandbox = {
    window: {},
    fetch: undefined
  };
  vm.createContext(sandbox);
  vm.runInContext(setupSrc, sandbox, { filename: setupPath });
  const demo = sandbox.window.AIADemo || {};
  const howIds = (demo.how || []).map((d) => d.id);
  const extraIds = (demo.extra || []).map((d) => d.id);
  ok(JSON.stringify(howIds) === JSON.stringify(HOW), "HOW ids are exact and ordered");
  ok(JSON.stringify(extraIds) === JSON.stringify(EXTRA), "EXTRA ids are exact and ordered");
  ok((demo.desks || []).length === HOW.length + EXTRA.length, "65 default desks");

  const vita = (demo.desks || []).find((d) => d.id === "vita");
  ok(vita && vita.label === "Insurance", "vita label stays Insurance");
  ok(vita && vita.family === "Quote It Away", "vita family stays Quote It Away");

  (demo.cards ? demo.cards() : []).forEach((row) => {
    const c = row.card || {};
    ok(/Desk does not send\./.test(String(c.draft || "")), "draft says desk does not send");
    ok(/@example\.com$/.test(String(c.email || "")), "email stays @example.com");
    ok(/^417-555-01/.test(String(c.phone || "")), "phone stays 417-555-01xx");
    ok(!/\bVita Financial\b/i.test((row.label || "") + " " + (row.display || "") + " " + (c.title || "") + " " + (c.notes || "") + " " + (c.draft || "")), "does not print Vita Financial");
  });

  const sandboxWithJson = {
    window: {},
    fetch: function () {
      return Promise.resolve({
        ok: true,
        json: function () {
          return Promise.resolve({
            desks: [{
              id: "unknown-demo",
              label: "Unknown demo desk",
              displayPack: "Unknown demo desk",
              family: "Automate It Away",
              does: "Unknown desk test fixture.",
              cards: [{
                title: "DEMO · Unknown demo desk · capture",
                step: "capture",
                contactName: "Pat Example",
                phone: "417-555-0199",
                email: "pat.unknown-demo@example.com",
                notes: "Unknown desk fixture.",
                draft: "Draft only. Desk does not send.",
                next: "Owner taps Stop."
              }]
            }]
          });
        }
      });
    }
  };
  vm.createContext(sandboxWithJson);
  vm.runInContext(setupSrc, sandboxWithJson, { filename: setupPath });
  await new Promise((resolve) => setTimeout(resolve, 0));
  await new Promise((resolve) => setTimeout(resolve, 0));
  const demoWithJson = sandboxWithJson.window.AIADemo || {};
  ok(!!(demoWithJson.find && demoWithJson.find("unknown-demo") && demoWithJson.find("unknown-demo").id === "unknown-demo"), "applyJson appends unknown desks from JSON");

  if (fails) {
    console.error(fails + " fail");
    process.exit(1);
  }
  console.log("demo-world/setup-demo checks passed");
}

main().catch((err) => {
  console.error("FAIL " + (err && err.stack || String(err)));
  process.exit(1);
});
